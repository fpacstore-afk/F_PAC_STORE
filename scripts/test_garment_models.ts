import assert from 'node:assert/strict';
import { garmentProfile, garmentProfiles, supplierSizeChart, garmentTitle } from '../shared/garmentModels';
import { allocateGarments, resolveGarmentBase } from '../shared/sharedGarmentStock';
import { cartAvailabilityIssues } from '../shared/cartAvailability';
import { getDb } from '../server/firebase';
import { initializeGarmentModels, transferGarmentModel } from '../server/services/garmentModels.service';
import { loadPublicCatalog } from '../server/services/publicCatalog.service';
import { calculateOrderPricing } from '../server/services/pricing.service';

const db: any = getDb();
const source = (id: string, supplier: string, name: string, measurements: string) => ({ id, supplier, name, kind: 'product', active: true, sizes: ['P','M','G','GG'], colors: ['Preto'], measurements, composition: 'Tecido de teste', weight: '240 g/m²' });
const entries = [source('ZIM-004','Zimm','Camiseta Suedine','M 68×52 M18'),source('TIG-002','Tiggas','Camiseta Suedine','M 56×71 M24'),source('ZIM-009','Zimm','Oversized Suedine','Medidas não informadas'),source('TIG-006','Tiggas','Oversized Suedine','M 54×74 M24')];
await db.collection('pricing_workbench').doc('catalog').set({ catalog: { entries }, version: 1 });
assert.equal(garmentProfile(entries[0])!.neckline, 'high_closed');
assert.equal(garmentProfile(entries[1])!.neckline, 'classic_open');
assert.equal(garmentProfiles({entries}).length, 4);
assert.deepEqual(supplierSizeChart(entries[0]).find(row=>row.size==='M'), {size:'M',length:'68 cm',width:'52 cm',sleeve:'18 cm'});
assert.deepEqual(supplierSizeChart(entries[1])[0], {size:'M',length:'71 cm',width:'56 cm',sleeve:'24 cm'});
assert.deepEqual(supplierSizeChart(entries[2]).find(row=>row.size==='M'),{size:'M',length:'73 cm',width:'55 cm',sleeve:'25 cm'});
assert.deepEqual(supplierSizeChart({...entries[2],id:'unknown-source'}),[], 'Unconfirmed source must remain empty');
assert.equal(garmentProfile({...entries[0],supplier:'Unknown'}),null);
const regata = garmentProfile(source('ZIM-010','Zimm','Linha Regata',''));
assert.equal(regata!.neckline,'tank');
assert.deepEqual(regata!.sizeChart.find(row=>row.size==='M'),{size:'M',length:'67 cm',width:'55 cm',sleeve:''});
assert.equal(regata!.gsm,'160 g/m²');
assert.equal(garmentTitle('Camisa', {garmentModelName:'Gola alta'}),'Camisa — Gola alta');

const mixed = {id:'mixed',slug:'mixed-pool',name:'Camiseta Tradicional F PAC',baseModel:'Tradicional Suedine',productFinish:'plain',status:'draft',primeBaseEnabled:true,sizes:['M'],colors:[{name:'Preto',hex:'#123456'}]};
const print = {id:'design',slug:'design',name:'Camiseta Tradicional F PAC',baseModel:'Tradicional Suedine',productFinish:'printed',status:'active',price:79.9,sizes:['M'],colors:[{name:'Preto',hex:'#123456'}],images:['shirt.jpg']};
await db.collection('products').doc('mixed').set(mixed);
await db.collection('products').doc('design').set(print);
await db.collection('inventory').doc('mixed-pool').set({variants:{Preto_M:{physicalQuantity:10,reservedQuantity:2,stock:10,available:true}}});
assert.equal((await initializeGarmentModels(db,'isolated')).created,4);
assert.equal((await initializeGarmentModels(db,'isolated')).created,0,'Initialization is repeatable');
const inv = async (id: string) => (await db.collection('inventory').doc(id).get()).data();
assert.equal((await inv('mixed-pool')).variants.Preto_M.physicalQuantity,10);
assert.deepEqual((await inv('garment-zim-004')).variants,{});
let catalog = await loadPublicCatalog(db);
assert.equal(catalog.availability['mixed-pool'].availableQuantity,0,'Mixed stock is preserved privately, not offered as a known supplier');
assert.equal(catalog.products[0]!.garmentOptions.length,2,'Both exact traditional source models offered separately');
assert.equal(catalog.products[0]!.garmentOptions[0].supplierName,undefined);
assert.equal(JSON.stringify(catalog).includes('Tecido de teste'),true);
const operation = {sourceId:'mixed',garmentModelId:'ZIM-004',variantKey:'Preto_M',quantity:3,expectedPhysicalQuantity:10,requestId:'transfer-1'};
assert.equal((await transferGarmentModel(db,operation,'isolated')).transferred,3);
assert.equal((await transferGarmentModel(db,operation,'isolated')).alreadyApplied,true);
assert.equal((await inv('mixed-pool')).variants.Preto_M.physicalQuantity,7);
assert.equal((await inv('mixed-pool')).variants.Preto_M.reservedQuantity,2,'Existing orders keep their reservations');
assert.equal((await inv('garment-zim-004')).variants.Preto_M.physicalQuantity,3);
assert.equal((await db.collection('products').doc('garment-zim-004').get()).data().colors.find((c: any)=>c.name==='Preto').hex,'#123456','Preserve actual source color');
await assert.rejects(transferGarmentModel(db,{...operation,quantity:9},'isolated'),/Identificador/);
await assert.rejects(transferGarmentModel(db,{...operation,quantity:6,expectedPhysicalQuantity:7,requestId:'too-many'},'isolated'),/reservas|saldo livre/i);
await assert.rejects(transferGarmentModel(db,{...operation,garmentModelId:'TIG-006',requestId:'wrong-family'},'isolated'),/compatível/);
await assert.rejects(transferGarmentModel(db,{...operation,requestId:'stale-balance'},'isolated'),/saldo mudou/);
catalog = await loadPublicCatalog(db);
assert.equal(catalog.availability['mixed-pool'].availableQuantity,0);
assert.equal(catalog.availability.design.availableQuantity,3);
assert.equal(catalog.products[0]!.sizeChart.length,0,'Unselected generic design has no borrowed size table');
const products = (await db.collection('products').get()).docs.map((doc: any)=>({...doc.data(),id:doc.id}));
const inventories = new Map<string,any>((await db.collection('inventory').get()).docs.map((doc: any)=>[doc.id,doc.data()]));
const line = {id:'design-model',productId:'design',slug:'design',garmentModelId:'ZIM-004',name:'Camisa',color:'Preto',size:'M',quantity:3};
const allocated = allocateGarments([line],products,inventories)[0];
assert.equal(allocated.stockBaseSlug,'garment-zim-004');
assert.match(allocated.name,/Gola alta/);
assert.throws(()=>allocateGarments([{...line,garmentModelId:'TIG-002'}],products,inventories),/insuficiente/,'No fallback to another supplier');
assert.throws(()=>allocateGarments([{...line,garmentModelId:undefined}],products,inventories),/Escolha um modelo/);
assert.equal(resolveGarmentBase({...print,garmentModelId:'ZIM-004',stockBaseSlug:'garment-tig-002'},products),undefined,'Explicit wrong source rejected');
const issues = cartAvailabilityIssues([{...line,stockBaseSlug:'garment-zim-004'}],(slug,key)=>catalog.availability[slug]?.variants[key]?.availableQuantity||0);
assert.deepEqual(issues,[],'Bag validates selected source rather than mixed product pool');
const priced = await calculateOrderPricing({items:[{...line,garmentModelName:'FORGED',quantity:1}],customerInfo:{} } as any,{priceOnly:true});
assert.equal(priced.verifiedItems[0].garmentModelId,'ZIM-004');
assert.match(priced.verifiedItems[0].name,/Gola alta/);
assert.ok(!priced.verifiedItems[0].name.includes('FORGED'));
await assert.rejects(calculateOrderPricing({items:[{...line,garmentModelId:'TIG-006'}],customerInfo:{}} as any,{priceOnly:true}),/indisponível/);
console.log('PASS supplier-specific identity and measurements, empty-pool initialization, conserved mixed stock, reservations, atomic/idempotent classification, stale balances, source isolation, public privacy, cart and authoritative checkout.');
