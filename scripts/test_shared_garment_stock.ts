import assert from 'node:assert/strict';
import { requireIsolatedTestDb } from './requireIsolatedTestDb';
import { resolveGarmentBase, allocateGarments } from '../shared/sharedGarmentStock';
import { cartAvailabilityIssues } from '../shared/cartAvailability';
import { reserveStock, releaseStockReservation, consumeStockReservation, checkStock } from '../server/services/store.service';
import { loadPublicCatalog } from '../server/services/publicCatalog.service';
import { transferGarmentsToProduction } from '../server/services/productionStock.service';
import { reconcileSharedStockEdit } from '../server/services/sharedStockEdit.service';
import { recordBulkStockMovement } from '../server/controllers/admin.controller';
import { saveInventoryCount, getInventoryOverview } from '../server/controllers/inventoryCount.controller';

const db = requireIsolatedTestDb();
// Firestore disallows reads after writes. The mock normally doesn't enforce this.
const transact = db.runTransaction.bind(db);
db.runTransaction = (callback: any) => transact((tx: any) => {
  let wrote = false;
  return callback({ ...tx, get: (ref: any) => { assert.equal(wrote, false, 'all transaction reads precede writes'); return tx.get(ref); }, set: (...args: any[]) => { wrote = true; return tx.set(...args); }, update: (...args: any[]) => { wrote = true; return tx.update(...args); } });
});
const base = { id: 'blank', slug: 'blank', name: 'Oversized lisa', status: 'draft', productFinish: 'plain', baseModel: 'Oversized Premium 240GSM', colors: [{ name: 'Preto' }, { name: 'Marrom' }], sizes: ['M', 'G'], primeBaseEnabled: true };
const product = (id: string) => ({ ...base, id, slug: id, name: id, productFinish: 'printed', status: 'active', price: 80, stampIds: ['not-yet-printed'] });
await db.collection('products').doc('blank').set(base);
for (const id of ['fp', 'eagle']) await db.collection('products').doc(id).set(product(id));
const variant = (n: number) => ({ physicalQuantity: n, reservedQuantity: 0, availableQuantity: n, stock: n, available: n > 0 });
await db.collection('inventory').doc('blank').set({ variants: { Preto_M: variant(10), Marrom_G: variant(3) } });
for (const id of ['fp', 'eagle']) await db.collection('inventory').doc(id).set({ variants: { Preto_M: variant(0) } });
await db.collection('designs').doc('not-yet-printed').set({ stockBalance: 0, stockBySize: { '8x6': 0 }, availableSizes: ['8x6'] });
const line = (id: string, quantity: number, color = 'Preto', size = 'M') => ({ id, productId: id, slug: id, parentSlug: id, name: id, color, size, quantity, price: 80, variantKey: `${color}_${size}` });
const order = (id: string, items: any[]) => ({ id, items, stockControl: 'move', inventoryLifecycle: 'reserved' });
const inv = async (id = 'blank') => (await db.collection('inventory').doc(id).get()).data();
const readOrder = async (id: string) => (await db.collection('orders').doc(id).get()).data();
let catalog = await loadPublicCatalog(db);
assert.equal(catalog.products.length, 2);
assert.equal(catalog.products[0]!.stockBaseSlug, 'blank');
assert.equal(catalog.availability.fp.variants.Preto_M.availableQuantity, 10);
assert.equal(catalog.availability.eagle.variants.Preto_M.availableQuantity, 10);
assert.equal((await checkStock([line('fp', 6), line('eagle', 5)])).isAvailable, false);
await assert.rejects(reserveStock('TOO-MANY', [line('fp', 6), line('eagle', 5)], undefined, order('TOO-MANY', [])), /insuficiente/);
assert.equal((await inv()).variants.Preto_M.reservedQuantity, 0);
assert.equal((await readOrder('TOO-MANY')), undefined);
const items = [line('fp', 3), line('eagle', 2), line('eagle', 1, 'Marrom', 'G')];
await reserveStock('A', items, undefined, order('A', items));
assert.equal((await inv()).variants.Preto_M.reservedQuantity, 5);
assert.equal((await inv()).variants.Marrom_G.reservedQuantity, 1, 'multiple variants of one base cannot overwrite each other');
assert.equal((await inv()).variants.Preto_M.physicalQuantity, 10);
catalog = await loadPublicCatalog(db);
assert.equal(catalog.availability.fp.variants.Preto_M.availableQuantity, 5);
assert.equal(catalog.availability.eagle.variants.Preto_M.availableQuantity, 5);
assert.equal((await db.collection('designs').doc('not-yet-printed').get()).data().stockBalance, 0, 'digital artwork never invents a physical print debit');
await reserveStock('A', items, undefined, order('A', items));
assert.equal((await inv()).variants.Preto_M.reservedQuantity, 5);
await db.collection('products').doc('fp').update({ stockMode: 'ready_only' });
await releaseStockReservation('A', items);
assert.equal((await inv()).variants.Preto_M.reservedQuantity, 0, 'cancellation uses original source snapshot even after catalog changes');
assert.equal((await inv()).variants.Marrom_G.reservedQuantity, 0);
await releaseStockReservation('A', items);
await db.collection('products').doc('fp').update({ stockMode: 'shared' });
await db.collection('inventory').doc('fp').set({ variants: { Preto_M: variant(2) } });
catalog = await loadPublicCatalog(db);
assert.equal(catalog.availability.fp.variants.Preto_M.availableQuantity, 10, 'old catalog quantities are not real ready stock until physically counted');
await db.collection('inventory').doc('fp').set({ variants: { Preto_M: { ...variant(2), physicalCountVerified: true } } });
const mixed = [line('fp', 3)];
await reserveStock('MIXED', mixed, undefined, order('MIXED', mixed));
assert.equal((await inv('fp')).variants.Preto_M.reservedQuantity, 2);
assert.equal((await inv()).variants.Preto_M.reservedQuantity, 1);
const mixedOrder = await readOrder('MIXED');
assert.deepEqual(mixedOrder.items[0].inventoryAllocations.map((a: any) => [a.source, a.quantity]), [['ready', 2], ['plain', 1]]);
await db.runTransaction((tx: any) => transferGarmentsToProduction(tx, db, 'MIXED', mixedOrder, 'estamparia'));
assert.equal((await inv()).variants.Preto_M.physicalQuantity, 9);
assert.equal((await inv()).variants.Preto_M.reservedQuantity, 0);
assert.equal((await inv('fp')).variants.Preto_M.physicalQuantity, 2, 'ready stock is untouched by printing');
await db.runTransaction((tx: any) => transferGarmentsToProduction(tx, db, 'MIXED', mixedOrder, 'ready'));
assert.equal((await inv()).variants.Preto_M.physicalQuantity, 9, 'production replay never consumes a blank twice');
assert.equal((await db.collection('production_stock').doc('MIXED').get()).data().status, 'ready');
await consumeStockReservation('MIXED', mixed);
assert.equal((await inv('fp')).variants.Preto_M.physicalQuantity, 0);
assert.equal((await inv()).variants.Preto_M.physicalQuantity, 9, 'shipping cannot consume the same blank again');
assert.equal((await db.collection('production_stock').doc('MIXED').get()).data().status, 'shipped');
const cancelItems = [line('eagle', 2)];
await reserveStock('CANCEL-PRODUCED', cancelItems, undefined, order('CANCEL-PRODUCED', cancelItems));
const cancelOrder = await readOrder('CANCEL-PRODUCED');
await db.runTransaction((tx: any) => transferGarmentsToProduction(tx, db, 'CANCEL-PRODUCED', cancelOrder, 'estamparia'));
await releaseStockReservation('CANCEL-PRODUCED', cancelItems);
assert.equal((await inv()).variants.Preto_M.physicalQuantity, 7, 'cancelled printed pieces do not return to the blank pool');
assert.equal((await db.collection('production_stock').doc('CANCEL-PRODUCED').get()).data().status, 'cancelled');
const custom = [{ ...line('manual-custom-uniform', 2), customProduct: true, customDetails: { model: 'Oversized' } }];
await reserveStock('MANUAL-EDIT', custom, undefined, order('MANUAL-EDIT', custom));
const saved = await readOrder('MANUAL-EDIT');
assert.equal(saved.items[0].inventoryAllocations[0].productSlug, 'blank');
await db.runTransaction(async (tx: any) => {
  const edited = await reconcileSharedStockEdit(tx, db, 'MANUAL-EDIT', saved, [{ ...custom[0], size: 'G', color: 'Marrom', variantKey: 'Marrom_G', quantity: 2 }], 1);
  tx.update(db.collection('orders').doc('MANUAL-EDIT'), { items: edited });
});
assert.equal((await inv()).variants.Preto_M.reservedQuantity, 0);
assert.equal((await inv()).variants.Marrom_G.reservedQuantity, 2);
await releaseStockReservation('MANUAL-EDIT', custom);
assert.equal((await inv()).variants.Marrom_G.reservedQuantity, 0, 'cancel uses edited allocation instead of obsolete caller item');
const ambiguous = { ...base, id: 'other', slug: 'other' };
assert.equal(resolveGarmentBase(product('fp'), [base, ambiguous]), undefined);
assert.equal(resolveGarmentBase({ ...product('fp'), stockBaseSlug: 'blank' }, [base, ambiguous])?.id, 'blank');
const forged = allocateGarments([{ ...line('eagle', 1), inventoryAllocations: [{ productSlug: 'fake', quantity: 1 }] }], [base, product('eagle')], new Map([['blank', await inv()], ['eagle', await inv('eagle')]]));
assert.equal(forged[0].inventoryAllocations[0].productSlug, 'blank');
catalog = await loadPublicCatalog(db);
const getStock = (id: string, key: string) => catalog.availability[id]?.variants[key]?.availableQuantity || 0;
assert.equal(cartAvailabilityIssues([line('fp', 4), line('eagle', 4)], getStock, catalog.products).length, 1, 'mixed designs share one cart limit');
assert.equal(cartAvailabilityIssues([line('fp', 3), line('eagle', 4)], getStock, catalog.products).length, 0);
const response = () => ({ statusCode: 200, body: {} as any, status(code: number) { this.statusCode = code; return this; }, json(body: any) { this.body = body; return this; } });
const countRes = response();
await saveInventoryCount({ body: { reference: '2026-10', counts: [{ productSlug: 'blank', variantKey: 'Preto_M', counted: 7 }, { productSlug: 'fp', variantKey: 'Preto_M', counted: 0 }] }, user: { uid: 'isolated' } } as any, countRes as any);
assert.equal(countRes.statusCode, 201);
assert.equal(countRes.body.differenceCount, 0);
const savedCount = (await db.collection('inventory_counts').doc(countRes.body.id).get()).data();
assert.equal(savedCount.lines.length, 2, 'zero balances and matching counts are preserved');
assert.equal((await inv()).variants.Preto_M.physicalQuantity, 7, 'saving a count cannot silently change physical stock');
assert.equal(savedCount.production.length, 1, 'cancelled personalized piece remains visible in monthly count');
const overview = response();
await getInventoryOverview({ query: { reference: '2026-10' } } as any, overview as any);
assert.equal(overview.body.latestCount.id, countRes.body.id);
console.log('PASS shared pool across all designs, mixed variants, ready-first allocation, no print-stock gate, idempotency, production, cancellation, shipping, custom edits, cart limits and persistent monthly inventory with strict transaction ordering.');

// Initial zeroing uses canonical bulk adjustments without pretending to count stock.
const productsBeforeReset = (await db.collection('products').get()).docs.length;
const ordersBeforeReset = (await db.collection('orders').get()).docs.length;
const countsBeforeReset = (await db.collection('inventory_counts').get()).docs.length;
const productionBeforeReset = (await db.collection('production_stock').get()).docs.length;
const resetRequest = { body: { productSlug: 'blank', updates: [{ variantKey: 'Preto_M', quantity: 0 }, { variantKey: 'Marrom_G', quantity: 0 }], reason: 'Zeragem inicial — aguardando contagem física', idempotencyKey: 'initial-reset-test-001' }, user: { uid: 'isolated' } } as any;
const resetResponse = response();
await recordBulkStockMovement(resetRequest, resetResponse as any);
assert.equal(resetResponse.statusCode, 200);
assert.equal((await inv()).variants.Preto_M.physicalQuantity, 0);
assert.equal((await inv()).variants.Marrom_G.availableQuantity, 0);
const movementCount = (await db.collection('stock_movements').get()).docs.length;
await recordBulkStockMovement(resetRequest, response() as any);
assert.equal((await db.collection('stock_movements').get()).docs.length, movementCount, 'retry never duplicates the adjustment history');
for (const [collection, expected] of [['products', productsBeforeReset], ['orders', ordersBeforeReset], ['inventory_counts', countsBeforeReset], ['production_stock', productionBeforeReset]] as const) assert.equal((await db.collection(collection).get()).docs.length, expected, `${collection} is preserved`);
await db.collection('inventory').doc('reserved-base').set({ variants: { Preto_M: { ...variant(2), reservedQuantity: 1, availableQuantity: 1 } } });
const reservedReset = response();
await recordBulkStockMovement({ ...resetRequest, body: { ...resetRequest.body, productSlug: 'reserved-base', updates: [{ variantKey: 'Preto_M', quantity: 0 }], idempotencyKey: 'initial-reset-test-002' } }, reservedReset as any);
assert.equal(reservedReset.statusCode, 400);
assert.equal((await inv('reserved-base')).variants.Preto_M.physicalQuantity, 2);
console.log('PASS initial bulk zeroing preserves catalog, orders, production, counts and audit idempotency, and protects active reservations.');
