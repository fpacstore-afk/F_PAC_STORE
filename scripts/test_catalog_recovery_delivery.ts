const product = { colors: [{ name: 'Preto' }, { name: 'Bege' }], sizes: ['P', 'M'] };
const available = (key?: string) => key === undefined || key === 'Preto_M';
assert.equal(catalogVariantAvailable(product, 'Bege', 'M', available), false, 'aggregate stock must not make a sold-out combination available');
assert.equal(catalogVariantAvailable(product, 'Preto', 'M', available), true);
assert.equal(catalogVariantAvailable(product, '', 'M', available), true);
assert.equal(catalogVariantAvailable(product, 'Bege', '', available), false);
assert.equal(catalogVariantAvailable(product, '', '', available), true);
const params = new URLSearchParams('q=camisa&color=Preto&size=M&available=1&sort=price-asc&min=50&line=force');
const restoredFilters = readCatalogFilters(new URLSearchParams(params.toString()));
assert.equal(restoredFilters.colorFilter, 'Preto'); assert.equal(restoredFilters.sizeFilter, 'M');
assert.equal(restoredFilters.search, 'camisa'); assert.equal(restoredFilters.hideOutOfStock, true);
assert.equal(restoredFilters.sortBy, 'price-asc');
assert.equal(new URL(catalogProductLink('https://fpacstore.com.br/product/test', 'Off White', 'GG')).searchParams.get('color'), 'Off White');
assert.equal(readCatalogFilters(new URLSearchParams('sort=unknown&min=NaN')).minPrice, '');
assert.equal(catalogCreatedTime('2026-10-16T12:00:00Z') > catalogCreatedTime('2026-10-15T12:00:00Z'), true);
const sizes = resolveProductSizeChart('oversized', [{ size: 'M', length: '77 cm', width: '57 cm', sleeve: '25 cm' }], ['M', 'GG']);
assert.equal(sizes[0].length, '77 cm', 'product measurements must override model defaults');
assert.equal(sizes[1].length, '', 'never invent measurements absent from a custom chart');
assert.deepEqual(resolveProductSizeChart('oversized', undefined, ['P', 'M']).map(row => row.size), ['P', 'M']);
assert.equal(emailDeliveryLabel('sent'), 'Aceito pelo provedor');
assert.equal(emailDeliveryLabel('delivered'), 'Entregue ao servidor');
assert.equal(emailDeliveryLabel('opened'), 'Entregue ao servidor');
assert.equal(emailDeliveryLabel('bounced'), 'Devolvido');

