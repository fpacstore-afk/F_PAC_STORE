import assert from 'node:assert/strict';
import { manualWhatsAppUrl, notificationChannelStatus } from '../shared/notificationContacts';
import { requireIsolatedTestDb } from './requireIsolatedTestDb';
const db = requireIsolatedTestDb();
const { saveProductionNotificationSettings, getProductionNotificationSettings, prepareManualOrderWhatsApp } = await import('../server/services/productionNotification.service');
const { testProductionNotification, saveProductionSettings } = await import('../server/controllers/automation.controller');
const { createManualOrderController } = await import('../server/controllers/admin.controller');
const { sendOrderReceivedEmail } = await import('../server/services/email.service');
const response = () => ({ statusCode: 200, body: null as any, status(code: number) { this.statusCode = code; return this; }, json(body: any) { this.body = body; return this; } });

await saveProductionNotificationSettings({ emailEnabled: true, whatsappEnabled: false, testEmail: ' SECONDARY@EXAMPLE.INVALID ', testPhone: '(47) 99746-5602', templates: { received: 'Mensagem salva para {{nome_cliente}}: pedido {{numero_pedido}}.' } });
let settings = await getProductionNotificationSettings();
assert.equal(settings.testEmail, 'secondary@example.invalid');
assert.equal(settings.testPhone, '5547997465602');
await saveProductionNotificationSettings({ templates: { estamparia: 'Nova mensagem' } });
assert.equal((await getProductionNotificationSettings()).testEmail, 'secondary@example.invalid');
let res = response();
await saveProductionSettings({ body: { testEmail: 'endereço-inválido' } } as any, res as any);
assert.equal(res.statusCode, 400);
assert.equal((await getProductionNotificationSettings()).testEmail, 'secondary@example.invalid');

let calls: any[] = [], providerFails = false;
process.env.RESEND_API_KEY = 're_isolated_test';
delete process.env.EVOLUTION_API_URL;
delete process.env.EVOLUTION_API_KEY;
globalThis.fetch = async (input: any, init: any) => {
  assert.match(String(input), /^https:\/\/api\.resend\.com\//);
  const body = JSON.parse(init.body); calls.push(body);
  assert.doesNotMatch(body.html, /<script>/);
  return new Response(JSON.stringify(providerFails ? { name: 'validation_error', message: 'Provider rejected test' } : { id: 'isolated-email-id' }), { status: providerFails ? 422 : 200, headers: { 'Content-Type': 'application/json' } });
};
res = response();
await testProductionNotification({ body: { stageId: 'ready', channel: 'email', customTemplate: 'Texto atualizado <script>alert(1)</script> {{numero_pedido}}' } } as any, res as any);
assert.equal(res.body.emailSent, true);
assert.equal(res.body.emailId, 'isolated-email-id');
assert.deepEqual(calls[0].to, ['secondary@example.invalid']);
assert.match(calls[0].text, /TESTE-999/);
assert.match(calls[0].html, /&lt;script&gt;/);
res = response();
await testProductionNotification({ body: { stageId: 'ready', channel: 'whatsapp_manual' } } as any, res as any);
assert.equal(res.body.manualOnly, true);
assert.equal(res.body.whatsappSent, false);
assert.equal(calls.length, 1, 'manual WhatsApp must not call any provider');
const url = new URL(res.body.whatsappUrl);
assert.equal(url.pathname, '/5547997465602');
assert.match(url.searchParams.get('text')!, /TESTE • PEDIDO DE EXEMPLO/);
assert.equal(new URL(manualWhatsAppUrl('+55 (47) 99746-5602', 'Texto & cor + tamanho')).searchParams.get('text'), 'Texto & cor + tamanho');
assert.throws(() => manualWhatsAppUrl('123', 'Teste'), /DDD/);
providerFails = true;
res = response();
await testProductionNotification({ body: { stageId: 'ready', channel: 'email' } } as any, res as any);
assert.equal(res.statusCode, 502); assert.equal(res.body.emailSent, false);
delete process.env.RESEND_API_KEY;
res = response();
await testProductionNotification({ body: { stageId: 'ready', channel: 'email' } } as any, res as any);
assert.equal(res.statusCode, 503); assert.equal(res.body.emailSent, false);

process.env.RESEND_API_KEY = 're_isolated_test'; providerFails = false;
await db.collection('orders').doc('TEST-EMAIL-FLOW').set({ customerName: 'Cliente', customerEmail: 'customer@example.invalid', status: 'received', paymentStatus: 'approved', total: 101.30, subtotal: 89.90, shipping: 11.40, shippingCost: 17.00, customerPhone: '47997465602', items: [{ name: 'Camiseta', price: 89.90, quantity: 1 }] });
const automatic = await sendOrderReceivedEmail('TEST-EMAIL-FLOW');
assert.equal(automatic.emailSent, true);
const latest = calls.at(-1);
assert.deepEqual(latest.to, ['customer@example.invalid'], 'fixed test recipient must not replace customer recipient');
assert.match(latest.text, /Mensagem salva para CLIENTE: pedido TEST-EMAIL-FLOW/);
assert.match(latest.html, /11\.40/); assert.doesNotMatch(latest.html, />GRÁTIS<|entra em produção na mesma hora/);
const manual = await prepareManualOrderWhatsApp('TEST-EMAIL-FLOW');
assert.equal(manual.whatsappSent, false);
assert.match(new URL(manual.whatsappUrl).searchParams.get('text')!, /Mensagem salva/);
assert.equal((await db.collection('orders').doc('TEST-EMAIL-FLOW').get()).data().whatsappMessages, undefined);
const count = calls.length;
await sendOrderReceivedEmail('TEST-EMAIL-FLOW');
assert.equal(calls.length, count, 'automatic received email must be idempotent');
res = response();
await createManualOrderController({ body: { order: { id: 'MANUAL-TEST-EMAIL', customerName: 'Teste', customerEmail: 'manual@example.invalid', stockControl: 'no_move', status: 'received', total: 20, items: [{ id: 'custom-item', name: 'Produto', quantity: 1, price: 20 }] } }, user: { email: 'operator@example.invalid' } } as any, res as any);
assert.equal(res.statusCode, 201);
assert.deepEqual(calls.at(-1).to, ['manual@example.invalid']);
const manualCalls = calls.length;
res = response();
await createManualOrderController({ body: { order: { id: 'MANUAL-TEST-EMAIL', customerName: 'Teste', customerEmail: 'manual@example.invalid', stockControl: 'no_move', status: 'received', total: 20, items: [{ id: 'custom-item', name: 'Produto', quantity: 1, price: 20 }] } } } as any, res as any);
assert.equal(calls.length, manualCalls, 'manual-order replay must not notify the customer twice');
const events = await db.collection('automation_logs').get();
const log = events.docs.map((doc: any) => doc.data()).find((entry: any) => entry.orderId === 'TEST-EMAIL-FLOW');
assert.equal(log.emailSent, true); assert.equal(log.whatsappSent, false);
assert.equal(notificationChannelStatus(log, 'email'), 'Enviado');
assert.equal(notificationChannelStatus({ event: 'production.stage_notification' }, 'email'), 'Sem confirmação');
assert.equal(notificationChannelStatus({ message: 'Avisos do pedido #123: WhatsApp Não configurado; e-mail Erro' }, 'email'), 'Erro');
assert.equal(notificationChannelStatus({ message: 'Avisos do pedido #123: WhatsApp Não configurado; e-mail Enviado' }, 'whatsapp'), 'Não configurado');
console.log('PASS persistent test contacts; safe manual WhatsApp; provider acceptance and rejection; current templates; real customer recipients; email idempotency and truthful channel logs.');
