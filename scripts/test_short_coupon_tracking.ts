import assert from 'node:assert/strict';
import { parseOrderTrackingInput, safeTrackingUrl } from '../shared/trackingInput.ts';
import { DEFAULT_STAGE_TEMPLATES, resolveSavedStageTemplates } from '../shared/productionNotificationDefaults.ts';
import { renderStageTemplate } from '../src/constants/notificationTemplates.ts';
import { getDb } from '../server/firebase.ts';
import { issueCoupon } from '../server/services/postPurchase.service.ts';

assert.deepEqual(parseOrderTrackingInput('#PAC-123'), { orderId: 'PAC-123', token: '' });
assert.deepEqual(parseOrderTrackingInput('https://fpacstore.com.br/order/PAC-123?token=abc'), { orderId: 'PAC-123', token: 'abc' });
assert.deepEqual(parseOrderTrackingInput('PAC-123', 'https://www.fpacstore.com.br/order/PAC-123?token=abc'), { orderId: 'PAC-123', token: 'abc' });
assert.deepEqual(parseOrderTrackingInput('https://fpacstore.com.br/#/order/PAC-123?token=abc'), { orderId: 'PAC-123', token: 'abc' });
assert.throws(() => parseOrderTrackingInput('https://evil.example/order/PAC-123?token=abc'));
assert.throws(() => parseOrderTrackingInput('PAC-456', 'https://fpacstore.com.br/order/PAC-123?token=abc'));
assert.equal(safeTrackingUrl('javascript:alert(1)'), 'https://fpacstore.com.br/tracking');
assert.equal(resolveSavedStageTemplates({ shipped: 'F PAC STORE · 🚚 *Pedido #{{numero_pedido}} enviado*\nRastreio: {{link_rastreio}}\nAcompanhe: {{link_acompanhamento}}' }).shipped, DEFAULT_STAGE_TEMPLATES.shipped);
assert.equal(resolveSavedStageTemplates({ shipped: 'Texto personalizado' }).shipped, 'Texto personalizado');
const message = renderStageTemplate(DEFAULT_STAGE_TEMPLATES.shipped, { id: 'PAC-123', trackingCode: 'AB123BR', publicTrackingUrl: 'https://fpacstore.com.br/order/PAC-123?token=abc' });
assert.ok(message.includes('AB123BR'));
assert.ok(message.includes('todas as letras e números'));
assert.ok(message.includes('/order/PAC-123?token=abc'));
const db = getDb();
const order = { id: 'short', customerEmail: 'test@example.com' };
const short = await issueCoupon(order);
assert.match(short.code, /^FP[0-9A-F]{6}$/);
assert.equal(short.bonusPercent, 5);
assert.equal(Date.parse(short.expiresAt) - Date.parse(short.createdAt), 7 * 86400000);
assert.equal((await issueCoupon(order)).code, short.code);
await db.collection('post_purchase_coupons').doc('return_old').set({ code: 'VOLTAE797384A04', status: 'active', expiresAt: new Date(Date.now() + 86400000).toISOString() });
assert.equal((await issueCoupon({ id: 'old' })).code, 'VOLTAE797384A04');
console.log('Short coupon and customer tracking input regression checks passed.');
