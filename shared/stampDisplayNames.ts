const normalize = (value: unknown) => String(value ?? '').trim().normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '').replace(/[–—]/g, '-').replace(/\s+/g, ' ').toLowerCase();

export function getStampDisplayName(stamp: StampNameSource): string {
  const current = String(stamp.name ?? '').trim();
  const approved = approvedStampDisplayNames.find(entry => entry.id === stamp.id);
  // An unrelated/new stamp or a later deliberate rename must keep its own name.
  if (!approved || ![approved.originalName, approved.name].some(name => normalize(name) === normalize(current))) return current;
  return approved.name;
}

export function getStampSearchAliases(stamp: StampNameSource): string[] {
  const tags = Array.isArray(stamp.tags) ? stamp.tags.filter((tag): tag is string => typeof tag === 'string') : [];
  return [...new Set([String(stamp.name ?? '').trim(), getStampDisplayName(stamp), ...tags].filter(Boolean))];
}

